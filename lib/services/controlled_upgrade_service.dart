  static String _sanitize(String value) {
    var safe = value.trim();
    safe = safe.replaceAll(
      RegExp(
        r'\b(?:sk-|nvapi-|github_pat_)[A-Za-z0-9_-]+',
        caseSensitive: false,
      ),
      '[REDACTED_SECRET]',
    );
    safe = safe.replaceAll(
      RegExp(
        r'\b(?:api[_ -]?key|access[_ -]?token|token|password|secret|credential)\s*[:=]\s*[^\s,;]+',
        caseSensitive: false,
      ),
      '[REDACTED_SECRET]',
    );
    return safe.length > 500 ? '${safe.substring(0, 500)}…' : safe;
  }

  static Future<Map<String, dynamic>> _runExistingWorker({
    required String repoPath,
    required List<String> allowedFiles,
    required String task,
    required Map<String, dynamic>? proposal,
    required bool apply,
  }) async {
    try {
      final tempDir = await Directory.systemTemp.createTemp(
        'agent_cypher_upgrade_',
      );
      final proposalFile = File('${tempDir.path}/proposal.json');
      final args = <String>[
        'tools/nemotron_coding_worker.py',
        '--repo',
        repoPath,
        '--task',
        task,
      ];
      for (final file in allowedFiles) {
        args.addAll(['--file', file]);
      }
      if (apply) {
        final proposalPath = proposal?['proposal_file'] as String?;
        if (proposalPath == null || proposalPath.isEmpty) {
          throw StateError(
            'The worker proposal file was unavailable for apply.',
          );
        }
        args.addAll(['--apply-proposal', proposalPath]);
      } else {
        args.addAll(['--proposal-file', proposalFile.path]);
      }
      final stopwatch = Stopwatch()..start();
      final result = await Process.run(
        'python3',
        args,
        workingDirectory: repoPath,
      );
      stopwatch.stop();
      final output = result.stdout is String ? result.stdout as String : '';
      TaskTelemetryService.shared.recordWorkspaceCommand(
        command: ['python3', ...args].join(' '),
        workingDirectory: repoPath,
        exitCode: result.exitCode,
        elapsedMs: stopwatch.elapsedMilliseconds,
        output: result.exitCode == 0 ? output : result.stderr.toString(),
      );
      if (result.exitCode != 0) {
        throw StateError(_sanitize(result.stderr.toString()));
      }
      final decoded = jsonDecode(output.trim());
      if (decoded is! Map) {
        throw const FormatException('Worker output was not JSON.');
      }
      final map = Map<String, dynamic>.from(decoded);
      if (!apply && await proposalFile.exists()) {
        map['proposal'] = jsonDecode(await proposalFile.readAsString());
        map['proposal']['proposal_file'] = proposalFile.path;
      }
      return map;
    } on Object catch (error) {
      return {'ok': false, 'error': _sanitize('$error')};
    }
  }

  static Future<UpgradeValidationResult> _runValidation(String repoPath) async {
    try {
      final flutter = const String.fromEnvironment(
        'FLUTTER_BIN',
        defaultValue: 'flutter',
      );
      final commands = <List<String>>[
        [flutter, 'analyze', '--no-fatal-infos'],
        [flutter, 'test'],
      ];
      final evidence = <String>[];
      for (final command in commands) {
        final stopwatch = Stopwatch()..start();
        final result = await Process.run(
          command.first,
          command.skip(1).toList(),
          workingDirectory: repoPath,
        ).timeout(const Duration(minutes: 5));
        stopwatch.stop();
        TaskTelemetryService.shared.recordWorkspaceCommand(
          command: command.join(' '),
          workingDirectory: repoPath,
          exitCode: result.exitCode,
          elapsedMs: stopwatch.elapsedMilliseconds,
          output: result.exitCode == 0
              ? result.stdout.toString()
              : result.stderr.toString(),
        );
        evidence.add('${command.skip(1).join(' ')}: exit ${result.exitCode}');
        if (result.exitCode != 0) {
          return UpgradeValidationResult(
            passed: false,
            evidence: evidence.join('; '),
          );
        }
      }
      return UpgradeValidationResult(
        passed: true,
        evidence: evidence.join('; '),
      );
    } on Object catch (error) {
      return UpgradeValidationResult(
        passed: false,
        evidence: 'Validation unavailable or timed out: ${_sanitize('$error')}',
      );
    }
  }
